using System;
using StArray.ModManager.Il2Cpp;
using StArray.ModManager.Manager;
using StArray.ModManager.RuntimeAbstractions;

namespace FirstPersonCamera.Port.Runtime;

/// <summary>
/// Cached binds for the Unity / game members the original mod consumed through desktop interop
/// assemblies.
///
/// On Android no such reference DLLs exist — the metadata lives inside the APK's
/// <c>global-metadata.dat</c>. Every member is resolved once against the live runtime and reused;
/// <see cref="Invalidate"/> drops the cache after a scene change.
///
/// <b>Image names.</b> The desktop build read these types out of MelonLoader-generated interop
/// assemblies (<c>Il2CppCinemachine.dll</c>, <c>Il2CppHLAutoGenerated.dll</c>). Those files do not
/// exist on the device, and their names are <i>not</i> the names il2cpp reports — a game's images are
/// usually the single <c>Assembly-CSharp.dll</c>, with Unity/Cinemachine living in
/// <c>UnityEngine.*.dll</c> or in the game assembly itself depending on how it was built. So each
/// lookup runs through <see cref="ClassIndex"/>, which tries a list of plausible images and then falls
/// back to a namespace+name scan over every loaded image. Nothing here is pinned to a desktop-only
/// assembly name.
/// </summary>
public static class GameApi
{
    // Unity ship names — these really are the image names il2cpp reports for engine modules.
    internal const string CoreModule = "UnityEngine.CoreModule.dll";
    internal const string InputModule = "UnityEngine.InputLegacyModule.dll";

    /// <summary>Images that may contain gameplay code (the game assembly, plus HDRP/HL aliases).</summary>
    internal static readonly string[] GameImages =
    {
        "Assembly-CSharp.dll",
        "HLRuntime.dll",
        "Hardlight.dll",
    };

    // UnityEngine.Object
    public static nint ObjectFindObjectsOfTypeType;
    public static nint ObjectFindObjectsOfTypeTypeBool;
    public static nint ObjectGetComponentType;
    public static nint ObjectGetComponentsInChildrenTypeBool;

    // UnityEngine.Camera
    public static nint CameraMain;

    // UnityEngine.Time
    public static nint TimeFrameCount;
    public static nint TimeTime;
    public static nint TimeUnscaledTime;
    public static nint TimeDeltaTime;

    // UnityEngine.Input (legacy) — still what the game's input layer exposes.
    public static nint InputGetKeyDown;
    public static nint InputGetAxisRaw;

    // Types
    public static nint ActorClass;
    public static nint CharacterClass;
    public static nint CameraManagerClass;
    public static nint CinemachineBrainClass;
    public static nint RendererClass;
    public static nint TransformClass;
    public static nint MonoBehaviourClass;

    // CinemachineCameraManager members
    public static nint CameraManagerMainCamera;
    public static nint CameraManagerCinemachineBrain;

    // Hardlight.Actor members
    public static nint ActorAttachPoints;
    public static nint ActorVisualProxy;
    public static nint AttachPointsTryGetNodeTransform;

    public static bool Ready { get; private set; }

    private static bool _attempted;

    /// <summary>Resolves every binding. Safe to call repeatedly; no-op once successful.</summary>
    public static bool Initialise()
    {
        if (_attempted && Ready) return true;
        _attempted = true;

        try
        {
            var objectClass = ClassIndex.Find("UnityEngine", "Object");
            TransformClass = ClassIndex.Find("UnityEngine", "Transform");
            RendererClass = ClassIndex.Find("UnityEngine", "Renderer");
            MonoBehaviourClass = ClassIndex.Find("UnityEngine", "MonoBehaviour");

            ObjectFindObjectsOfTypeType = Il2Cpp.FindMethodInHierarchy(objectClass, "FindObjectsOfType", 1);
            ObjectFindObjectsOfTypeTypeBool = Il2Cpp.FindMethodInHierarchy(objectClass, "FindObjectsOfType", 2);
            ObjectGetComponentType = Il2Cpp.FindMethodInHierarchy(objectClass, "GetComponent", 1);
            ObjectGetComponentsInChildrenTypeBool = Il2Cpp.FindMethodInHierarchy(objectClass, "GetComponentsInChildren", 2);

            var camera = ClassIndex.Find("UnityEngine", "Camera");
            CameraMain = Il2Cpp.FindMethodInHierarchy(camera, "get_main", 0);

            var time = ClassIndex.Find("UnityEngine", "Time");
            TimeFrameCount = Il2Cpp.FindMethodInHierarchy(time, "get_frameCount", 0);
            TimeTime = Il2Cpp.FindMethodInHierarchy(time, "get_time", 0);
            TimeUnscaledTime = Il2Cpp.FindMethodInHierarchy(time, "get_unscaledTime", 0);
            TimeDeltaTime = Il2Cpp.FindMethodInHierarchy(time, "get_deltaTime", 0);

            var input = ClassIndex.Find("UnityEngine", "Input");
            InputGetKeyDown = Il2Cpp.FindMethodInHierarchy(input, "GetKeyDown", 1);
            InputGetAxisRaw = Il2Cpp.FindMethodInHierarchy(input, "GetAxisRaw", 1);

            ActorClass = ClassIndex.Find("Hardlight", "Actor");
            CharacterClass = ClassIndex.Find("Hardlight", "Character");

            // Cinemachine ships as source in many Unity projects (so it lands in the game assembly)
            // and as a package in others (its own image). The index covers both.
            CameraManagerClass = ClassIndex.Find("Cinemachine", "CinemachineCameraManager");
            CinemachineBrainClass = ClassIndex.Find("Cinemachine", "CinemachineBrain");

            CameraManagerMainCamera = Il2Cpp.FindMethodInHierarchy(CameraManagerClass, "get_MainCamera", 0);
            CameraManagerCinemachineBrain = Il2Cpp.FindMethodInHierarchy(CameraManagerClass, "get_CinemachineBrain", 0);

            ActorAttachPoints = Il2Cpp.FindMethodInHierarchy(ActorClass, "get_ActorAttachPoints", 0);
            ActorVisualProxy = Il2Cpp.FindMethodInHierarchy(ActorClass, "get_VisualProxy", 0);

            var attachPointsClass = ClassIndex.Find("Hardlight", "ActorAttachPoints");
            AttachPointsTryGetNodeTransform = Il2Cpp.FindMethodInHierarchy(attachPointsClass, "TryGetNodeTransform", 2);

            Ready = CameraMain != 0 && TimeFrameCount != 0 && ObjectFindObjectsOfTypeType != 0;
            Logger.Info("GameApi", Ready
                ? $"Bindings resolved: Actor=0x{ActorClass:X} CameraManager=0x{CameraManagerClass:X} Brain=0x{CinemachineBrainClass:X} Renderer=0x{RendererClass:X}"
                : "Bindings incomplete — first-person camera will stay idle until the game world loads.");
            return Ready;
        }
        catch (Exception ex)
        {
            Logger.Error("GameApi", $"Initialise: {ex}");
            Ready = false;
            return false;
        }
    }

    public static void Invalidate()
    {
        _attempted = false;
        Ready = false;
        Il2Cpp.InvalidateCaches();
        ClassIndex.Clear();
        GameApi.InvalidateLocal();
    }

    /// <summary>Clears the member pointers while keeping the image/class index warm.</summary>
    private static void InvalidateLocal()
    {
        ObjectFindObjectsOfTypeType = 0;
        ObjectFindObjectsOfTypeTypeBool = 0;
        ObjectGetComponentType = 0;
        ObjectGetComponentsInChildrenTypeBool = 0;
        CameraMain = 0;
        TimeFrameCount = 0;
        TimeTime = 0;
        TimeUnscaledTime = 0;
        TimeDeltaTime = 0;
        InputGetKeyDown = 0;
        InputGetAxisRaw = 0;
        ActorClass = 0;
        CharacterClass = 0;
        CameraManagerClass = 0;
        CinemachineBrainClass = 0;
        RendererClass = 0;
        TransformClass = 0;
        MonoBehaviourClass = 0;
        CameraManagerMainCamera = 0;
        CameraManagerCinemachineBrain = 0;
        ActorAttachPoints = 0;
        ActorVisualProxy = 0;
        AttachPointsTryGetNodeTransform = 0;
    }

    /// <summary><c>il2cpp_class_get_type</c> + <c>il2cpp_type_get_object</c> for <c>System.Type</c> args.</summary>
    internal static nint TypeObject(nint klass)
    {
        if (klass == 0) return 0;
        var type = Il2CppFunctions.il2cpp_class_get_type(klass);
        return type == 0 ? 0 : Il2CppFunctions.il2cpp_type_get_object(type);
    }
}

/// <summary>Unity <c>Time</c> static reads.</summary>
public static class UnityTime
{
    public static int FrameCount
        => GameApi.TimeFrameCount != 0 ? Il2Cpp.InvokeStaticInt(GameApi.TimeFrameCount, null) : Environment.TickCount;

    public static double TimeSeconds
        => GameApi.TimeTime != 0 ? Il2Cpp.InvokeStaticDouble(GameApi.TimeTime, null) : 0d;

    public static double UnscaledTime
        => GameApi.TimeUnscaledTime != 0 ? Il2Cpp.InvokeStaticDouble(GameApi.TimeUnscaledTime, null) : 0d;

    public static float DeltaTime
        => GameApi.TimeDeltaTime != 0 ? Il2Cpp.InvokeStaticFloat(GameApi.TimeDeltaTime, null) : 0f;
}

/// <summary>
/// GameObject/Component helpers. Uses the non-generic <c>System.Type</c> overloads so nothing has
/// to be inflated at runtime — one code path for every component type.
/// </summary>
public static class UnityApi
{
    /// <summary><c>UnityEngine.Object.FindObjectsOfType(Type)</c>.</summary>
    public static nint[] FindObjectsOfType(nint typeClass, bool includeInactive = false)
    {
        if (typeClass == 0) return Array.Empty<nint>();

        var typeObj = GameApi.TypeObject(typeClass);
        if (typeObj == 0) return Array.Empty<nint>();

        try
        {
            nint array = 0;
            if (includeInactive && GameApi.ObjectFindObjectsOfTypeTypeBool != 0)
            {
                var flag = 1;
                array = Il2Cpp.InvokeStatic(GameApi.ObjectFindObjectsOfTypeTypeBool,
                    new[] { typeObj, Il2Cpp.Addr(ref flag) });
            }

            if (array == 0 && GameApi.ObjectFindObjectsOfTypeType != 0)
                array = Il2Cpp.InvokeStatic(GameApi.ObjectFindObjectsOfTypeType, new[] { typeObj });

            return Il2Cpp.ToObjectPointers(array);
        }
        catch (Exception ex)
        {
            Logger.Warn("UnityApi", $"FindObjectsOfType: {ex.Message}");
            return Array.Empty<nint>();
        }
    }

    /// <summary><c>Component.GetComponentsInChildren(Type, bool)</c>.</summary>
    public static nint[] GetComponentsInChildren(nint component, nint typeClass, bool includeInactive)
    {
        if (component == 0 || typeClass == 0) return Array.Empty<nint>();

        var typeObj = GameApi.TypeObject(typeClass);
        if (typeObj == 0 || GameApi.ObjectGetComponentsInChildrenTypeBool == 0) return Array.Empty<nint>();

        try
        {
            var flag = includeInactive ? 1 : 0;
            var array = Il2Cpp.InvokeInstance(component, GameApi.ObjectGetComponentsInChildrenTypeBool,
                new[] { typeObj, Il2Cpp.Addr(ref flag) });
            return Il2Cpp.ToObjectPointers(array);
        }
        catch
        {
            return Array.Empty<nint>();
        }
    }

    /// <summary><c>Component.GetComponent(Type)</c>.</summary>
    public static nint GetComponent(nint component, nint typeClass)
    {
        if (component == 0 || typeClass == 0 || GameApi.ObjectGetComponentType == 0) return 0;
        var typeObj = GameApi.TypeObject(typeClass);
        if (typeObj == 0) return 0;

        try { return Il2Cpp.InvokeInstance(component, GameApi.ObjectGetComponentType, new[] { typeObj }); }
        catch { return 0; }
    }

    /// <summary>Filters a set of component pointers down to those assignable to <paramref name="baseClass"/>.</summary>
    public static bool IsAssignableTo(nint obj, nint baseClass)
        => obj != 0 && baseClass != 0 && Il2Cpp.IsAssignableTo(Il2Cpp.ObjectGetClass(obj), baseClass);

    /// <summary>Unity <c>Camera.main</c>.</summary>
    public static nint MainCamera
    {
        get
        {
            if (GameApi.CameraMain == 0) return 0;
            try { return Il2Cpp.InvokeStatic(GameApi.CameraMain, null); }
            catch { return 0; }
        }
    }

    /// <summary>World position → Unity screen point (origin bottom-left).</summary>
    public static bool TryWorldToScreen(nint camera, Vec3 world, out Vec3 screen)
    {
        screen = default;
        if (camera == 0) return false;

        var method = Il2Cpp.FindMethodInHierarchy(Il2Cpp.ObjectGetClass(camera), "WorldToScreenPoint",
            m => Il2CppNative.GetParamCount(m) == 1);
        if (method == 0) return false;

        var arg = world;
        try
        {
            screen = Il2Cpp.InvokeInstanceUnbox<Vec3>(camera, method, new[] { Il2Cpp.Addr(ref arg) });
            return true;
        }
        catch { return false; }
    }
}
